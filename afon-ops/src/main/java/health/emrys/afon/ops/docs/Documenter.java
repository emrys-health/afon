package health.emrys.afon.ops.docs;

import health.emrys.afon.config.AfonPropertyProvider;
import health.emrys.afon.config.AfonUserProvider;
import health.emrys.afon.config.Redacter;
import health.emrys.afon.ops.steps.Step;
import health.emrys.afon.ops.steps.StepOperations;
import health.emrys.afon.ops.steps.StepRunner;
import org.apache.commons.io.FileUtils;
import org.apache.commons.io.file.PathUtils;
import org.jspecify.annotations.NonNull;
import org.slf4j.Logger;

import java.io.*;
import java.nio.file.Path;
import java.time.ZonedDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;

import static java.lang.String.format;
import static org.slf4j.LoggerFactory.getLogger;

public class Documenter {

    private static final Logger logger = getLogger(Documenter.class);

    private final AfonPropertyProvider properties;
    private final AfonUserProvider users;

    public Documenter(AfonPropertyProvider properties, AfonUserProvider users) {
        this.properties = properties;
        this.users = users;
    }

    public void generateDocuments(List<DocumentMetadata> documents) {
        for ( DocumentMetadata document : documents) {
            writeDocumentToFile(document.getFilename(), getContent(document));
        }
    }

    String getContent(DocumentMetadata documentMetadata) {
        return generateContent(documentMetadata, new ByteArrayOutputStream());
    }

    private void writeDocumentToFile(String fileName, String document) {
        try {
            File docsDir = docsDir();
            Path docPath = Path.of(docsDir.toString(), fileName);
            deleteIfExists(docPath);
            writeToFile(docPath, document);
        } catch (IOException e) {
            logger.error("Failed to write document to file " + fileName, e);
        }
    }

    @NonNull File docsDir() {
        Path docs = Path.of("target/docs");
        File dir = docs.toFile();
        if (!dir.exists()) {
            logger.info("Creating directory {}", dir.getAbsolutePath());
            dir.mkdirs();
        }
        return dir;
    }

    private void deleteIfExists(Path path) throws IOException {
        if (path.toFile().exists()) {
            logger.info("Deleting document {}", path);
            PathUtils.delete(path);
        }
    }

    private void writeToFile(Path path, String document) throws IOException {
        logger.info("Writing document to {}", path.toString());
        FileUtils.writeStringToFile(path.toFile(), document);
    }

    private String generateContent(DocumentMetadata documentMetadata, OutputStream os) {
        appendTo(os, documentMetadata.getDescription());
        appendTo(os, format("""
               This is an autogenerated file created at %s 
               """, ZonedDateTime.now().format(DateTimeFormatter.ofPattern("yyyy/MM/dd HH:mm:ss"))));
        appendTo(os, """
                # Steps
                The individual steps are:
                """);
        writeSteps(documentMetadata, os);
        appendTo(os, documentMetadata.getFurtherNotes());
        String document = os.toString();
        return Redacter.redactSecrets(document, documentMetadata.getFilename(), properties.getSecretProperties());
    }

     private void writeSteps(DocumentMetadata documentMetadata, OutputStream fos) {
        List<Step> steps = documentMetadata.steps(new StepOperations(new DocumentingStepActions(fos), properties, users));
        new StepRunner(users).runSteps(steps.stream().map(x -> decorating(x, fos, documentMetadata.sectionHeading(x))).toList());
    }

    private Step decorating(Step step, OutputStream outputStream, String sectionHeading) {
        return new Step(step.getName(), step.getDescription(), () -> {
            if (sectionHeading != null) {
                appendTo(outputStream, format("## %s", sectionHeading));
            }
            appendTo(outputStream, format("### %s", capitalizeFirst(step.getDescription())));
            step.getFunction().run();
        });
    }

    private void appendTo(OutputStream stream, String content) {
        try (PrintWriter writer = new PrintWriter(stream)) {
            writer.println(content);
            writer.flush();
        }
    }

    private String capitalizeFirst(String input) {
        if (input == null || input.isEmpty()) {
            return input;
        }
        return Character.toUpperCase(input.charAt(0)) + input.substring(1);
    }

}
