import { dump } from "js-yaml";
import type { DeploymentDraft } from "./model";

/**
 * Builds the afon-deployment.yaml document from form state, omitting empty
 * optionals so the output stays diff-friendly and schema-clean.
 */
export function buildConfig(draft: DeploymentDraft): Record<string, unknown> {
  const config: Record<string, unknown> = {
    apiVersion: "afon/v1",
    deployment: prune({
      name: draft.name,
      clusterName: draft.clusterName || undefined,
    }),
    clouds: draft.clouds.map((c) =>
      prune({
        id: c.id,
        provider: c.provider,
        region: c.region,
        storage: pruneMap(c.storage),
        polaris: pruneMap(c.polaris),
      })
    ),
  };
  if (draft.catalogs.length > 0) {
    config.catalogs = draft.catalogs.map((c) =>
      prune({
        name: c.name,
        cloud: c.cloud,
        type: c.type,
        via: c.type === "federated" ? c.via : undefined,
        bucketOverride: c.bucketOverride || undefined,
        testFixture: c.testFixture || undefined,
      })
    );
  }
  if (draft.engines.length > 0) {
    config.queryEngines = draft.engines.map((e) =>
      e.type === "snowflake"
        ? prune({
            type: e.type,
            jdbcUrlRef: e.jdbcUrlRef,
            readsCatalogs: e.readsCatalogs?.length ? e.readsCatalogs : undefined,
          })
        : prune({ type: e.type, target: e.target, workers: e.workers })
    );
  }
  if (draft.workbench) {
    const wb = draft.workbench;
    config.workbench = prune({
      type: wb.type,
      target: wb.target,
      domain: wb.domain,
      auth: wb.auth
        ? prune({
            provider: wb.auth.provider,
            emailDomain: wb.auth.emailDomain || undefined,
            clientIdRef: wb.auth.clientIdRef || undefined,
            clientSecretRef: wb.auth.clientSecretRef || undefined,
            cookieSecretRef: wb.auth.cookieSecretRef || undefined,
          })
        : undefined,
    });
  }
  if (draft.secretsFile) {
    config.secretsFile = draft.secretsFile;
  }
  return config;
}

export function toYaml(config: Record<string, unknown>): string {
  return (
    "# Generated by afon-ui. Review, commit, then deploy with the CLI.\n" +
    "# See docs/config_driven_architecture.md.\n" +
    dump(config, { lineWidth: 100, noRefs: true })
  );
}

function prune<T extends Record<string, unknown>>(obj: T): T {
  const out = {} as T;
  for (const [k, v] of Object.entries(obj)) {
    if (v !== undefined && v !== "") (out as Record<string, unknown>)[k] = v;
  }
  return out;
}

function pruneMap(map: Record<string, string>): Record<string, string> {
  return Object.fromEntries(Object.entries(map).filter(([, v]) => v !== ""));
}
