package health.emrys.afon.demo;

import org.apache.commons.io.file.PathUtils;
import org.slf4j.Logger;

import java.io.*;
import java.nio.file.Path;
import java.util.List;
import java.time.ZonedDateTime;
import java.time.format.DateTimeFormatter;

import static java.lang.String.format;
import static org.slf4j.LoggerFactory.getLogger;

public class Documenter {

    private static final Logger log = getLogger(Documenter.class);

    private final DocumentMetadata  documentMetadata;

    public Documenter(DocumentMetadata documentMetadata) {
        this.documentMetadata = documentMetadata;
    }

    public static String capitalizeFirst(String input) {
        if (input == null || input.isEmpty()) {
            return input;
        }
        return Character.toUpperCase(input.charAt(0)) + input.substring(1);
    }

    public void writeDocumentation() {
        String fileName = documentMetadata.getFilename();
        try {
            Path targetPath  = Path.of("target");
            File target = targetPath.toFile();
            if (!target.exists()) {
                log.info("Creating directory {}", target.getAbsolutePath());
                target.mkdirs();
            }
            Path path = Path.of(targetPath.toString(), fileName);
            if (path.toFile().exists()) {
                log.info("Deleting {}", path);
                PathUtils.delete(path);
            }
            writeTo(path.toString());
        } catch (IOException e) {
            log.error("Could not write to " +  fileName, e);
        }
    }

    private void writeTo(String fileName) throws IOException {
        log.info("Writing to {}", fileName);
        try (OutputStream os = new FileOutputStream(fileName)) {
            printTo(os, documentMetadata.getDescription());
            printTo(os, format("""
                               
                               This is an autogenerated file create at %s 
                               """, ZonedDateTime.now().format(DateTimeFormatter.ofPattern("yyyy/MM/dd HH:mm:ss"))));
            printTo(os, "# Steps");
            writeSteps(os);
            printTo(os, documentMetadata.getFurtherNotes());
        }
    }

    private void writeSteps(OutputStream fos) {
        StepOperations stepOperations = new StepOperations(new StepDocumentation(fos));
        List<Step>     steps          = documentMetadata.steps(stepOperations);
        StepRunner     app            = new StepRunner();
        app.runSteps(steps.stream().map(x -> decorating(x, fos)).toList());
    }

    private Step decorating(Step step, OutputStream outputStream) {
        return new Step(step.name, step.description, () -> {
            printTo(outputStream, format("### %s", capitalizeFirst(step.description)));
            step.function.run();
        });
    }

    private void printTo(OutputStream fos, String msg) {
        final PrintWriter writer = new PrintWriter(fos);
        writer.println(msg);
        writer.flush();
    }

}
