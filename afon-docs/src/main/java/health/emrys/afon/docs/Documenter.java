package health.emrys.afon.docs;

import health.emrys.afon.config.AfonPropertiesLoader;
import health.emrys.afon.ops.steps.Step;
import health.emrys.afon.ops.steps.StepDocumentation;
import health.emrys.afon.ops.steps.StepOperations;
import health.emrys.afon.ops.steps.StepRunner;
import org.apache.commons.io.FileUtils;
import org.apache.commons.io.file.PathUtils;
import org.jspecify.annotations.NonNull;
import org.slf4j.Logger;

import java.io.*;
import java.nio.file.Path;
import java.time.ZonedDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.Properties;

import static java.lang.String.format;
import static org.slf4j.LoggerFactory.getLogger;

public class Documenter {

    private static final Logger logger = getLogger(Documenter.class);

    private final DocumentMetadata documentMetadata;

    public Documenter(DocumentMetadata documentMetadata) {
        this.documentMetadata = documentMetadata;
    }

    public void writeDocumentation() {
        String document = generateDocument(new ByteArrayOutputStream());
        writeDocumentToFile(document);
    }

    void writeDocumentToFile(String document) {
        String fileName = documentMetadata.getFilename();
        try {
            File docsDir = docsDir();
            Path docPath = Path.of(docsDir.toString(), fileName);
            deleteIfExists(docPath);
            writeToFile(docPath, document);
        } catch (IOException e) {
            logger.error("Could not write document " + fileName, e);
        }
    }

    @NonNull File docsDir() {
        Path docs = Path.of("target/docs");
        File dir = docs.toFile();
        if (!dir.exists()) {
            logger.info("Creating directory {}", dir.getAbsolutePath());
            dir.mkdirs();
        }
        return dir;
    }

    private void deleteIfExists(Path path) throws IOException {
        if (path.toFile().exists()) {
            logger.info("Deleting document {}", path);
            PathUtils.delete(path);
        }
    }

    private void writeToFile(Path path, String document) throws IOException {
        logger.info("Writing document to {}", path.toString());
        FileUtils.writeStringToFile(path.toFile(), document);
    }

    private String generateDocument(OutputStream os) {
        writeTo(os, documentMetadata.getDescription());
        writeTo(os, format("""
               
               
               This is an autogenerated file create at %s 
               """, ZonedDateTime.now().format(DateTimeFormatter.ofPattern("yyyy/MM/dd HH:mm:ss"))));
        writeTo(os, """
                # Steps
                If you really wanted to, you could run the individual steps by hand. They are:
                """);
        writeSteps(os);
        writeTo(os, documentMetadata.getFurtherNotes());
        String document = os.toString();
        return redactSecrets(document);
    }

    private String redactSecrets(String document) {
        Properties secretProperties   = new AfonPropertiesLoader().getSecretProperties();
        for (String key : secretProperties.stringPropertyNames()){
            String  original = document;
            String value = secretProperties.getProperty(key);
            if ( redactable(value) ) {
                document = document.replace(value, format("<%s>", key.toLowerCase()));
            }
            if (!original.equals(document)) {
                logger.info("Redacted property value {} of key {}", value, key);
            }
        }
        return document;
    }

    private boolean redactable(String value) {
        return !value.matches("afon|emrys|will");
    }

    private void writeSteps(OutputStream fos) {
        List<Step> steps = documentMetadata.steps(new StepOperations(new StepDocumentation(fos)));
        new StepRunner().runSteps(steps.stream().map(x -> decorating(x, fos)).toList());
    }

    private Step decorating(Step step, OutputStream outputStream) {
        return new Step(step.getName(), step.getDescription(), () -> {
            writeTo(outputStream, format("### %s", capitalizeFirst(step.getDescription())));
            step.getFunction().run();
        });
    }

    private void writeTo(OutputStream stream, String content) {
        try (PrintWriter writer = new PrintWriter(stream)) {
            writer.println(content);
            writer.flush();
        }
    }

    private String capitalizeFirst(String input) {
        if (input == null || input.isEmpty()) {
            return input;
        }
        return Character.toUpperCase(input.charAt(0)) + input.substring(1);
    }

}
