package health.emrys.afon.docs;

import health.emrys.afon.config.AfonPropertiesLoader;
import health.emrys.afon.steps.Step;
import health.emrys.afon.steps.StepDocumentation;
import health.emrys.afon.steps.StepOperations;
import health.emrys.afon.steps.StepRunner;
import org.apache.commons.io.file.PathUtils;
import org.jspecify.annotations.NonNull;
import org.slf4j.Logger;

import java.io.*;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.List;
import java.time.ZonedDateTime;
import java.time.format.DateTimeFormatter;
import java.util.Properties;

import static java.lang.String.format;
import static org.slf4j.LoggerFactory.getLogger;

public class Documenter {

    private static final Logger log = getLogger(Documenter.class);

    private final DocumentMetadata documentMetadata;

    public Documenter(DocumentMetadata documentMetadata) {
        this.documentMetadata = documentMetadata;
    }

    public static String capitalizeFirst(String input) {
        if (input == null || input.isEmpty()) {
            return input;
        }
        return Character.toUpperCase(input.charAt(0)) + input.substring(1);
    }

    public void writeDocumentation() {
        String fileName = documentMetadata.getFilename();
        try {
            Path targetPath = documentationPath();
            File target     = targetPath.toFile();
            if (!target.exists()) {
                log.info("Creating directory {}", target.getAbsolutePath());
                target.mkdirs();
            }
            Path path = Path.of(targetPath.toString(), fileName);
            if (path.toFile().exists()) {
                log.info("Deleting {}", path);
                PathUtils.delete(path);
            }
            writeTo(path.toString());
        } catch (IOException e) {
            log.error("Could not write to " + fileName, e);
        }
    }

    static @NonNull Path documentationPath() {
        String docsDir = "docs";
        Path   docs    = Path.of(docsDir);
        if (!docs.toFile().exists()) {
            String absolutePathModule = docs.toFile().getAbsolutePath();
            log.info("No directory '{}'. Looking in parent",
                     absolutePathModule);
            docs = Paths.get("").toAbsolutePath().getParent().resolve(docsDir);
            if (!docs.toFile().exists()) {
                throw new RuntimeException(format("Cannot find directory %s nor %s",
                                                  absolutePathModule,
                                                  docs.toFile().getAbsolutePath()));
            }
        }
        return docs;
    }

    private void writeTo(String fileName) throws IOException {
        log.info("Writing to {}", fileName);
        try (OutputStream os = new FileOutputStream(fileName);
             PrintWriter writer = new PrintWriter(os);) {
            writer.println(generateDocument());
        }
    }

    private String generateDocument() {
        try (ByteArrayOutputStream os = new ByteArrayOutputStream()) {
            printTo(os, documentMetadata.getDescription());
            printTo(os, format("""
                                   
                                   This is an autogenerated file create at %s 
                                   """, ZonedDateTime.now().format(DateTimeFormatter.ofPattern("yyyy/MM/dd HH:mm:ss"))));
            printTo(os, """
                # Steps
                If you really wanted to, you could run the individual steps by hand. They are:
                """);
            writeSteps(os);
            printTo(os, documentMetadata.getFurtherNotes());
            return redact(os.toString());
        } catch (IOException e) { // shouldn't happen as it's in-memory
            log.error("Could not write documentation", e);
            throw new RuntimeException(e);
        }
    }

    private static String redact(String documentation) {
        Properties cofidential   = new AfonPropertiesLoader().getConfidentialProperties();
        for (String verboten : cofidential
                .values()
                .stream()
                .map(x -> x.toString())
                .filter(x -> !x.equals("emrys")) // this is innocent although we should change OAUTH2_CLIENT_ID
                .toList()) {
            String  old = documentation;
            documentation = documentation.replace(verboten, "REDACTED");
            if (!old.equals(documentation)) {
                log.info("Redacted {}", verboten);
            }
        }
        return documentation;
    }

    private void writeSteps(OutputStream fos) {
        StepOperations stepOperations = new StepOperations(new StepDocumentation(fos));
        List<Step>     steps          = documentMetadata.steps(stepOperations);
        StepRunner app            = new StepRunner();
        app.runSteps(steps.stream().map(x -> decorating(x, fos)).toList());
    }

    private Step decorating(Step step, OutputStream outputStream) {
        return new Step(step.getName(), step.getDescription(), () -> {
            printTo(outputStream, format("### %s", capitalizeFirst(step.getDescription())));
            step.getFunction().run();
        });
    }

    private void printTo(OutputStream fos, String msg) {
        try (PrintWriter writer = new PrintWriter(fos)) {
            writer.println(msg);
            writer.flush();
        }
    }

}
